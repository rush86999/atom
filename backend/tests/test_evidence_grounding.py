def test_rules_state_the_negative_and_middle_paths():
    assert "Negative path" in EVIDENCE_GROUNDING_RULE
    assert "Middle path" in EVIDENCE_GROUNDING_RULE
    assert "conversation" in EVIDENCE_GROUNDING_RULE.lower()
    # the middle path has TWO forms: confirmation-in-progress wording and
    # asking for the missing information (a question asserts nothing)
    assert "ask for the missing information" in EVIDENCE_GROUNDING_RULE
    assert "no claim in either direction" in EVIDENCE_GROUNDING_RULE
    assert "Never upgrade an instruction to verify" in EVIDENCE_GROUNDING_RULE
    assert "Never upgrade an instruction to verify" in CANVAS_ARTIFACT_GROUNDING_RULE
    assert "Asking the reader FOR the missing detail" in CANVAS_ARTIFACT_GROUNDING_RULE
    # the confirm→assert regeneration correction offers both forms too
    from integrations import chat_orchestrator as co
    qwen_src = inspect.getsource(co.ChatOrchestrator._get_qwen_response)
    assert qwen_src.count("ask for the missing information") >= 2


