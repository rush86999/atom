"""Evidence-grounding contract (core/evidence_grounding.py) and its wiring.

Live incident (2026-09-02, Mark Kellam canvas): the instruction "confirm
480V 3-phase specs" (internal guidance mail) was regenerated by the drafting
turn as an assertion — "the machines we discussed are available in 480V
3-phase configuration" — with zero supporting evidence. Conversation is not
evidence: when a claim can't be grounded, the reply must take the negative
path (say it's unverified) or the middle path (confirmation-in-progress
wording that asserts nothing).
"""

from __future__ import annotations

import inspect

from core.evidence_grounding import (
    CANVAS_ARTIFACT_GROUNDING_RULE,
    EVIDENCE_GROUNDING_RULE,
    asserts_unverified_confirmation,
)


# ───────────────── confirm→assert detector ─────────────────

def test_detector_fires_on_the_live_incident():
    instruction = (
        "generate the draft — the response should confirm 480V 3 phase "
        "availability for the machines"
    )
    draft = (
        "Hi Mark,\n\nYes, the machines we discussed are available in 480V "
        "3-phase configuration."
    )
    assert asserts_unverified_confirmation(instruction, draft)


def test_detector_fires_on_assertion_variants():
    instruction = "draft a reply confirming the voltage specs"
    assert asserts_unverified_confirmation(
        instruction, "Good news: the unit is available in 480V configuration.")
    assert asserts_unverified_confirmation(
        instruction, "This has been confirmed with the manufacturer.")
    assert asserts_unverified_confirmation(
        instruction, "The machines are compatible with your power supply.")


def test_detector_stays_silent_on_middle_path():
    """The required fix — confirmation-in-progress wording asserts nothing."""
    instruction = "draft a reply confirming the voltage specs"
    middle = (
        "Hi Mark,\n\nWe are confirming 480V 3-phase availability and will "
        "follow up with the detailed specs for your machines."
    )
    assert not asserts_unverified_confirmation(instruction, middle)


def test_detector_stays_silent_on_ask_for_info_middle_path():
    """Asking for the missing information is the other middle path — a
    question makes no claim in either direction, even when it contains an
    assertion-marker phrase like "is available"."""
    instruction = "draft a reply confirming the voltage specs"
    ask = (
        "Hi Mark,\n\nTo make sure we recommend the right machine, could you "
        "share the spec sheets so we can confirm whether the units are "
        "available in 480V 3-phase configuration?"
    )
    assert not asserts_unverified_confirmation(instruction, ask)
    # mixed draft: declarative claim + questions still trips — the live
    # incident looked exactly like this
    mixed = (
        "Hi Mark,\n\nYes, the machines we discussed are available in 480V "
        "3-phase configuration. Could you confirm the material you cut?"
    )
    assert asserts_unverified_confirmation(instruction, mixed)


def test_detector_stays_silent_on_negative_path():
    instruction = "draft a reply confirming the voltage specs"
    negative = (
        "Hi Mark,\n\nI can't confirm the 480V 3-phase configuration from "
        "the data available — could you share the machine spec sheets?"
    )
    assert not asserts_unverified_confirmation(instruction, negative)


def test_detector_requires_a_confirm_instruction():
    # No confirm/verify ask in the instruction → an availability statement
    # is just an answer (grounded or not is the model's burden, not this
    # detector's).
    assert not asserts_unverified_confirmation(
        "what machines do you have", "The LCP8080 is available in 480V.")


def test_detector_ignores_empty_inputs():
    assert not asserts_unverified_confirmation("", "The machines are available.")
    assert not asserts_unverified_confirmation("confirm the specs", "")


