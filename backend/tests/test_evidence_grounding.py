def test_provenance_reaches_editor_and_conversational_paths():
    import inspect

    from integrations import chat_orchestrator as co

    # editor path: plan_canvas_edit takes provenance, orchestrator passes it
    from core import chat_canvas_editor as cce
    assert "provenance" in inspect.signature(cce.plan_canvas_edit).parameters
    edit_src = inspect.getsource(co.ChatOrchestrator._try_canvas_edit)
    assert "provenance=provenance" in edit_src

    # conversational path: _get_qwen_response takes it and renders the block
    qwen_src = inspect.getsource(co.ChatOrchestrator._get_qwen_response)
    assert "canvas_provenance" in inspect.signature(
        co.ChatOrchestrator._get_qwen_response).parameters
    assert "CANVAS ORIGIN" in qwen_src

    # chat route hydrates it from the create-audit row
    from integrations import chat_routes as cr
    route_src = inspect.getsource(cr)
    assert "canvas_provenance" in inspect.getsource(cr.send_chat_message)
    assert "_canvas_provenance_context" in route_src
