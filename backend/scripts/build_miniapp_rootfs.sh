#!/usr/bin/env bash
# build_miniapp_rootfs.sh — operator-run mini-app rootfs builder.
#
# Docker is a BUILD-TIME host tool ONLY — it constructs the ext4 rootfs image.
# It is NEVER the mini-app runtime (mini apps boot in Firecracker microVMs).
#
# Usage:
#   scripts/build_miniapp_rootfs.sh --base            # build the base template
#   scripts/build_miniapp_rootfs.sh <app_id>          # build a per-app rootfs
#
# For <app_id>: reads the app's manifest from the DB (via a tiny Python probe),
# writes a Dockerfile (FROM base_image, pip install -r requirements, COPY the
# guest agent, non-root user), then:
#   docker build → docker create → docker export (into a unique temp dir)
#   → tar extract → mkfs.ext4 -d <dir> (size allocated from the real tree)
#   → e2fsck validation → atomic mv → $MINIAPP_ROOTFS_DIR/miniapp-<app_id>.ext4.
# A failed or invalid build never touches an already-published image.
#
# Boot path: the microVM kernel execs /opt/atom-guest/agent.py directly, so the
# image ships an executable /bin/sh wrapper at that exact path. PID 1 often has
# a PATH that excludes the interpreter's directory (e.g. /usr/local/bin on the
# Debian python images), so the wrapper embeds the ABSOLUTE python3 path
# discovered inside the image during the build, keeps the original guest agent
# beside it as /opt/atom-guest/agent_main.py, and mounts /proc before exec.
#
# For --base: builds data/firecracker/miniapp-base.ext4 with just Python 3.11 +
# the guest agent (used when a mini app declares no dependencies).
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
cd "$REPO_ROOT"

MINIAPP_ROOTFS_DIR="${MINIAPP_ROOTFS_DIR:-data/mini_app_rootfs}"
FIRECRACKER_DATA_DIR="${FIRECRACKER_DATA_DIR:-data/firecracker}"
BASE_IMAGE="${MINIAPP_BASE_IMAGE:-python:3.11-slim}"
GUEST_AGENT="core/sandbox_runtime/firecracker_guest/agent.py"

# Per-build assets; always cleared by the EXIT trap, even on failure.
BUILD_TMPDIR=""      # docker export tarball + extracted tree
CTX_TMPDIR=""        # Dockerfile build context
DOCKER_TAG=""        # unique per-build image tag (never ":latest")
DOCKER_CONTAINER=""  # unique per-build container name
PUBLISH_TMP=""       # staging .ext4 next to the final path (atomic mv)

die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

cleanup() {
  local rc=$?
  if [[ -n "$DOCKER_CONTAINER" ]]; then
    docker rm -f "$DOCKER_CONTAINER" >/dev/null 2>&1 || true
    DOCKER_CONTAINER=""
  fi
  if [[ -n "$DOCKER_TAG" ]]; then
    docker image rm -f "$DOCKER_TAG" >/dev/null 2>&1 || true
    DOCKER_TAG=""
  fi
  if [[ -n "$PUBLISH_TMP" ]]; then
    rm -f "$PUBLISH_TMP"
    PUBLISH_TMP=""
  fi
  if [[ -n "$BUILD_TMPDIR" ]]; then
    rm -rf "$BUILD_TMPDIR"
    BUILD_TMPDIR=""
  fi
  if [[ -n "$CTX_TMPDIR" ]]; then
    rm -rf "$CTX_TMPDIR"
    CTX_TMPDIR=""
  fi
  return "$rc"
}
trap cleanup EXIT

write_build_context() {
  local dir="$1" include_deps="$2"

  [[ -f "$GUEST_AGENT" ]] || die "guest agent not found: $GUEST_AGENT (expected repo-root relative path)"
  cp "$GUEST_AGENT" "$dir/agent.py" || die "cannot copy guest agent $GUEST_AGENT into $dir"

  # Shell startup wrapper template. During the image build, @@PYTHON@@ is
  # replaced with the absolute python3 path found in THAT image, so PID 1's
  # PATH (which may miss /usr/local/bin) never matters at boot.
  cat > "$dir/agent_wrapper.sh" <<'EOF'
#!/bin/sh
# Generated by build_miniapp_rootfs.sh during the image build.
# PID 1 may boot with a PATH that excludes the interpreter directory
# (e.g. /usr/local/bin on Debian python images), so exec the absolute
# interpreter path baked in at build time. Mount /proc before exec.
PY="@@PYTHON@@"
export PATH="/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"
[ -d /proc/self ] || mount -t proc proc /proc 2>/dev/null || true
exec "$PY" /opt/atom-guest/agent_main.py "$@"
EOF

  {
    cat <<'EOF'
ARG BASE_IMAGE=python:3.11-slim
FROM ${BASE_IMAGE}
RUN useradd -m app
EOF
    if [[ "$include_deps" == "yes" ]]; then
      cat <<'EOF'
COPY requirements.txt /tmp/requirements.txt
RUN pip install --no-cache-dir -r /tmp/requirements.txt
EOF
    fi
    cat <<'EOF'
COPY agent.py /opt/atom-guest/agent_main.py
COPY agent_wrapper.sh /opt/atom-guest/agent_wrapper.sh
RUN set -eux; \
    PY="$(command -v python3)"; \
    [ -n "$PY" ] || { echo "ERROR: no python3 interpreter in base image" >&2; exit 1; }; \
    sed "s|@@PYTHON@@|$PY|" /opt/atom-guest/agent_wrapper.sh > /opt/atom-guest/agent.py; \
    chmod 0755 /opt/atom-guest/agent.py; \
    rm -f /opt/atom-guest/agent_wrapper.sh
USER app
CMD ["/opt/atom-guest/agent.py"]
EOF
  } > "$dir/Dockerfile"
}

build_rootfs() {
  local dockerfile_dir="$1"   # dir containing Dockerfile
  local out_path="$2"         # target .ext4 path
  local base_image="$3"       # base image passed as --build-arg BASE_IMAGE

  command -v docker >/dev/null 2>&1 \
    || die "docker CLI not found in PATH — docker is required to construct the rootfs"
  if ! docker info >/dev/null 2>&1; then
    die "docker daemon unreachable (not running, or permission denied on the docker socket — try sudo or the 'docker' group)"
  fi
  command -v mkfs.ext4 >/dev/null 2>&1 \
    || die "mkfs.ext4 not found — install e2fsprogs; rootfs creation must run on a Linux host"
  command -v e2fsck >/dev/null 2>&1 \
    || die "e2fsck not found — install e2fsprogs"

  # Unique per-build docker assets: no shared tag, no container name collisions.
  local build_id="$(date +%s)-$$-${RANDOM}"
  local image_tag="atom-miniapp-rootfs:build-${build_id}"
  local container_name="miniapp-build-${build_id}"

  BUILD_TMPDIR="$(mktemp -d)" || die "mktemp -d failed (check TMPDIR permissions)"
  local rootfs_tar="$BUILD_TMPDIR/rootfs.tar"
  local rootfs_dir="$BUILD_TMPDIR/rootfs"

  DOCKER_TAG="$image_tag"
  echo ">>> docker build (base image: $base_image)" >&2
  if ! docker build --build-arg "BASE_IMAGE=$base_image" -t "$image_tag" "$dockerfile_dir" >&2; then
    die "docker build failed for $dockerfile_dir (base image: $base_image)"
  fi
  DOCKER_CONTAINER="$container_name"
  if ! docker create --name "$container_name" "$image_tag" >/dev/null; then
    die "docker create failed for image $image_tag"
  fi
  if ! docker export "$container_name" > "$rootfs_tar"; then
    die "docker export failed for container $container_name"
  fi
  if ! docker rm "$container_name" >/dev/null; then
    die "docker rm failed for container $container_name"
  fi
  DOCKER_CONTAINER=""
  if ! docker image rm "$image_tag" >/dev/null 2>&1; then
    echo "WARN: could not remove temporary image $image_tag" >&2
  fi
  DOCKER_TAG=""

  mkdir -p "$rootfs_dir" || die "cannot create extraction directory $rootfs_dir"
  # Skip /dev contents: device nodes cannot be extracted unprivileged and the
  # kernel provides devtmpfs at boot anyway.
  if ! tar -xpf "$rootfs_tar" -C "$rootfs_dir" --exclude='dev/*' --exclude='./dev/*'; then
    die "failed to extract docker export tarball into $rootfs_dir"
  fi
  rm -f "$rootfs_tar"

  # Validate the pieces the microVM boot path depends on — before mkfs.
  local guest_dir="$rootfs_dir/opt/atom-guest"
  [[ -d "$guest_dir" ]] || die "extracted rootfs has no /opt/atom-guest directory"
  [[ -f "$guest_dir/agent_main.py" ]] || die "extracted rootfs is missing sibling guest agent /opt/atom-guest/agent_main.py"
  [[ -f "$guest_dir/agent.py" ]] || die "extracted rootfs is missing startup wrapper /opt/atom-guest/agent.py"
  [[ -x "$guest_dir/agent.py" ]] || die "/opt/atom-guest/agent.py is not executable in the extracted rootfs"
  [[ "$(head -n 1 "$guest_dir/agent.py")" == "#!/bin/sh" ]] || die "/opt/atom-guest/agent.py is not a shell wrapper (unexpected shebang)"
  local guest_py
  if ! guest_py="$(sed -n 's/^PY="\(.*\)"$/\1/p' "$guest_dir/agent.py")" || [[ -z "$guest_py" ]]; then
    die "startup wrapper /opt/atom-guest/agent.py has no baked-in interpreter path"
  fi
  [[ -x "$rootfs_dir$guest_py" ]] || die "interpreter $guest_py baked into the wrapper is missing from the extracted rootfs"

  # Size the ext4 from the actual tree (2x + 128 MiB headroom, min 256 MiB).
  # mkfs.ext4 -d cannot infer a size from a directory target and fails without
  # an explicit block count, which is why the old tar-based invocation died.
  local used_kb fs_mb blocks
  if ! used_kb="$(du -sk "$rootfs_dir" | awk '{print $1}')"; then
    die "could not measure extracted rootfs size (du failed)"
  fi
  [[ "$used_kb" =~ ^[0-9]+$ ]] || die "could not measure extracted rootfs size (unexpected du output)"
  fs_mb=$(( used_kb / 1024 * 2 + 128 ))
  if (( fs_mb < 256 )); then fs_mb=256; fi
  blocks=$(( fs_mb * 256 ))  # 4096-byte blocks

  # Build the image out-of-place next to the final path (same filesystem) so a
  # failure anywhere above leaves any existing valid image untouched, and the
  # publish below is a single atomic rename.
  local out_dir out_name
  out_dir="$(dirname "$out_path")"
  out_name="$(basename "$out_path")"
  if [[ ! -d "$out_dir" ]] && ! mkdir -p "$out_dir"; then
    die "cannot create output directory $out_dir"
  fi
  [[ -w "$out_dir" ]] || die "output directory not writable: $out_dir"
  PUBLISH_TMP="$out_dir/.${out_name}.tmp.$$"
  rm -f "$PUBLISH_TMP"
  if ! mkfs.ext4 -F -q -b 4096 -i 8192 -d "$rootfs_dir" "$PUBLISH_TMP" "$blocks"; then
    die "mkfs.ext4 failed for $out_path (${fs_mb} MiB allocated from $(( used_kb / 1024 )) MiB tree)"
  fi
  if ! e2fsck -fn "$PUBLISH_TMP" >/dev/null 2>&1; then
    die "new rootfs image failed e2fsck validation: $PUBLISH_TMP"
  fi
  if ! mv -f "$PUBLISH_TMP" "$out_path"; then
    die "atomic publish failed: mv $PUBLISH_TMP -> $out_path"
  fi
  PUBLISH_TMP=""

  rm -rf "$BUILD_TMPDIR"
  BUILD_TMPDIR=""
  echo "Built rootfs → $out_path"
}

mkdir -p "$MINIAPP_ROOTFS_DIR" "$FIRECRACKER_DATA_DIR" \
  || die "cannot create output directories $MINIAPP_ROOTFS_DIR / $FIRECRACKER_DATA_DIR"

if [[ "${1:-}" == "--base" ]]; then
  CTX_TMPDIR="$(mktemp -d)" || die "mktemp -d failed (check TMPDIR permissions)"
  write_build_context "$CTX_TMPDIR" no
  build_rootfs "$CTX_TMPDIR" "$FIRECRACKER_DATA_DIR/miniapp-base.ext4" "$BASE_IMAGE"
  rm -rf "$CTX_TMPDIR"
  CTX_TMPDIR=""
  echo "Base template ready. Set FIRECRACKER_ROOTFS_TEMPLATE=$FIRECRACKER_DATA_DIR/miniapp-base.ext4"
  exit 0
fi

APP_ID="${1:?usage: build_miniapp_rootfs.sh <app_id> | --base}"
case "$APP_ID" in
  .|..|*/*) die "invalid app id: '$APP_ID'" ;;
esac

command -v python >/dev/null 2>&1 \
  || die "python not found in PATH — needed to read the app manifest from the DB"

if ! MANIFEST="$(PYTHONPATH="$REPO_ROOT" python - "$APP_ID" <<'PY'
import json, sys
from core.database import get_db_session
from core.models import MiniApp
app_id = sys.argv[1]
with get_db_session() as db:
    app = db.query(MiniApp).filter(MiniApp.id == app_id).first()
    if app is None:
        sys.exit("MiniApp not found: " + app_id)
    print(json.dumps(app.manifest or {}))
PY
)"; then
  die "failed to read MiniApp manifest for '$APP_ID' (database error or unknown app id)"
fi

if ! DEPS="$(printf '%s' "$MANIFEST" | python -c 'import json,sys; print("\n".join(json.load(sys.stdin).get("dependencies") or []))')"; then
  die "manifest for '$APP_ID' is not valid JSON (bad 'dependencies')"
fi
if ! APP_BASE_IMAGE="$(printf '%s' "$MANIFEST" | python -c 'import json,sys; print(json.load(sys.stdin).get("base_image") or "")')"; then
  die "manifest for '$APP_ID' is not valid JSON (bad 'base_image')"
fi
[[ -n "$APP_BASE_IMAGE" ]] || APP_BASE_IMAGE="$BASE_IMAGE"

CTX_TMPDIR="$(mktemp -d)" || die "mktemp -d failed (check TMPDIR permissions)"
if [[ -n "$DEPS" ]]; then
  write_build_context "$CTX_TMPDIR" yes
  printf '%s\n' "$DEPS" > "$CTX_TMPDIR/requirements.txt"
else
  write_build_context "$CTX_TMPDIR" no
fi

build_rootfs "$CTX_TMPDIR" "$MINIAPP_ROOTFS_DIR/miniapp-$APP_ID.ext4" "$APP_BASE_IMAGE"
rm -rf "$CTX_TMPDIR"
CTX_TMPDIR=""
echo "Per-app rootfs ready → $MINIAPP_ROOTFS_DIR/miniapp-$APP_ID.ext4"
echo "Now publish the app (publish verifies this rootfs exists)."
