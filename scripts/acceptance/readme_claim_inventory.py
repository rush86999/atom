#!/usr/bin/env python3
"""Frozen claim inventory for the README's marketed functional surface.

This is the *denominator* for the README feature-readiness campaign. It splits
the 17 capability categories in `README.md` into testable user operations. The
README is pinned by commit + SHA-256; the inventory refuses to build if either
moves, so the denominator cannot drift silently.

Consumers:
  * ``--build`` writes CLAIM_INVENTORY.json / CLAIM_INVENTORY.md
  * ``--merge results.json`` merges an acceptance run into the inventory and
    rewrites the two artifacts (status/evidence only; claim text is immutable)

Status vocabulary (deliberately narrow):
  verified              executed at the named user/API boundary; expected outcome observed
  partial               an early transition passed; the named later one did not
  failed                reproduced failure at the boundary
  unverified            no candidate-bound execution yet
  blocked_external      needs a real external account/permission (not a pass)
  environment_limited   cannot execute on this host (Firecracker, no lancedb, ...)
  architecture_only     implementation/claim exists only as an unexercised assertion
  inaccurate            the README wording overstates what the product does
"""
