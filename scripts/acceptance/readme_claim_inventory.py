def readme_identity() -> dict:
    raw = README.read_bytes()
    return {
        "path": str(README.relative_to(ROOT)),
        "sha256": hashlib.sha256(raw).hexdigest(),
        "commit": PINNED_README_COMMIT,
        "tag": PINNED_TAG,
        "lines": raw.decode("utf-8").count("\n") + 1,
    }


def build() -> dict:
    ident = readme_identity()
    if ident["sha256"] != PINNED_README_SHA256:
        raise SystemExit(
            f"README moved: {ident['sha256']} != pinned {PINNED_README_SHA256}. "
            "Freeze a new denominator deliberately; do not silently rescore.")
    ids = [claim["id"] for claim in CLAIMS]
    if len(ids) != len(set(ids)):
        raise SystemExit("duplicate claim ids in inventory")
    functional = [c for c in CLAIMS if c["category"] not in
                  {"security", "performance", "compatibility", "comparative"}]
    categories = {}
    for claim in CLAIMS:
        cat = categories.setdefault(claim["category"], {
            "total": 0, "verified": 0, "partial": 0, "failed": 0,
            "unverified": 0, "blocked_external": 0,
            "environment_limited": 0, "architecture_only": 0,
            "inaccurate": 0,
        })
        cat["total"] += 1
        cat[claim["status"]] = cat.get(claim["status"], 0) + 1
    return {
        "schema_version": 1,
        "title": "README feature-readiness claim inventory",
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "readme": ident,
        "denominator": {
            "eligible_functional": len(functional),
            "tracked_separately": len(CLAIMS) - len(functional),
            "rule": "Partial/failed/unverified/blocked/environment-limited do not "
                    "count as passing. Category count alone is never a score.",
        },
        "claims": CLAIMS,
        "categories": categories,
    }


def merge(results_path: Path) -> dict:
    doc = build()
    results = json.loads(results_path.read_text())
    by_id = {r["claim_id"]: r for r in results.get("results", results if isinstance(results, list) else [])}
    unknown = set(by_id) - {c["id"] for c in doc["claims"]}
    if unknown:
        raise SystemExit(f"results reference unknown claims: {sorted(unknown)}")
    for claim in doc["claims"]:
        result = by_id.get(claim["id"])
        if not result:
            continue
        claim["status"] = result["status"]
        claim["evidence"] = result.get("evidence", [])
        claim["blocker"] = result.get("blocker", "")
        claim["notes"] = result.get("notes", "")
    # recompute category table after the merge
    doc["categories"] = {}
    for claim in doc["claims"]:
        cat = doc["categories"].setdefault(claim["category"], {
            "total": 0, "verified": 0, "partial": 0, "failed": 0,
            "unverified": 0, "blocked_external": 0,
            "environment_limited": 0, "architecture_only": 0,
            "inaccurate": 0,
        })
        cat["total"] += 1
        cat[claim["status"]] = cat.get(claim["status"], 0) + 1
    doc["acceptance_run"] = {
        "results_file": str(results_path),
        "generated_at": results.get("generated_at"),
        "config": results.get("config"),
        "harness": results.get("harness"),
    }
    doc["score"] = score(doc)
    return doc


def score(doc: dict) -> dict:
    functional = [c for c in doc["claims"] if c["category"] not in
                  {"security", "performance", "compatibility", "comparative"}]
    verified = [c for c in functional if c["status"] == "verified"]
    return {
        "verified_functional": len(verified),
        "eligible_functional": len(functional),
        "percent": round(100.0 * len(verified) / len(functional), 1) if functional else 0.0,
    }


def render_md(doc: dict) -> str:
    lines = [
        "# README feature-readiness claim inventory",
        "",
        f"Generated: {doc['generated_at']}",
        "",
        f"README: `{doc['readme']['path']}` @ `{doc['readme']['commit']}` "
        f"(tag `{doc['readme']['tag']}`), sha256 `{doc['readme']['sha256']}`",
        "",
        f"Eligible functional claims: **{doc['denominator']['eligible_functional']}** · "
        f"tracked separately: {doc['denominator']['tracked_separately']}",
        "",
        "> " + doc["denominator"]["rule"],
        "",
    ]
    if doc.get("score"):
        s = doc["score"]
        lines += [f"**Verified functional: {s['verified_functional']}/"
                  f"{s['eligible_functional']} ({s['percent']}%)**", ""]
    lines += ["## Category coverage", "",
              "| Category | Total | Verified | Partial | Failed | Unverified | Blocked external | Env limited |",
              "|---|---|---|---|---|---|---|---|"]
    for name in sorted(doc["categories"]):
        cat = doc["categories"][name]
        lines.append(
            f"| {name} | {cat['total']} | {cat.get('verified', 0)} | "
            f"{cat.get('partial', 0)} | {cat.get('failed', 0)} | "
            f"{cat.get('unverified', 0)} | {cat.get('blocked_external', 0)} | "
            f"{cat.get('environment_limited', 0)} |")
    lines += ["", "## Claims", ""]
    current = None
    for claim in doc["claims"]:
        if claim["category"] != current:
            current = claim["category"]
            lines += ["", f"### {current}", "",
                      "| ID | README | Operation | Entry point | Status |",
                      "|---|---|---|---|---|"]
        lines.append(
            f"| {claim['id']} | L{claim['readme_line']} | {claim['operation']} | "
            f"`{claim['entry']}` | **{claim['status']}** |")
    lines += ["", "## Evidence details", ""]
    for claim in doc["claims"]:
        if claim["status"] == "unverified" and not claim["evidence"]:
            continue
        lines += [f"### {claim['id']} — {claim['status']}", "",
                  f"- Claim: {claim['readme_text']}",
                  f"- Acceptance: {claim['acceptance']}",
                  f"- Expected: {claim['expected']}"]
        if claim["blocker"]:
            lines.append(f"- Blocker: {claim['blocker']}")
        for ev in claim["evidence"]:
            lines.append(f"- Evidence: `{ev}`")
        lines.append("")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--merge", type=Path)
    parser.add_argument("--out-dir", type=Path, default=OUT)
    args = parser.parse_args()
    doc = merge(args.merge) if args.merge else build()
    args.out_dir.mkdir(parents=True, exist_ok=True)
    (args.out_dir / "CLAIM_INVENTORY.json").write_text(json.dumps(doc, indent=2) + "\n")
    (args.out_dir / "CLAIM_INVENTORY.md").write_text(render_md(doc))
    print(json.dumps({
        "claims": len(doc["claims"]),
        "eligible": doc["denominator"]["eligible_functional"],
        "categories": len(doc["categories"]),
        "score": doc.get("score"),
    }, indent=2))


if __name__ == "__main__":
    main()
